UPDATE collector_sources s
SET
    config = COALESCE(s.config, '{}'::jsonb) || jsonb_strip_nulls(jsonb_build_object(
        'catalog_type', c.catalog_type,
        'catalog_type_id', c.type_id,
        'validity_status', c.validity_status,
        'from_engine', c.from_engine,
        'source_origin', CASE LOWER(c.from_engine)
            WHEN 'no' THEN 'Main Source'
            WHEN 'yes' THEN 'Other Source'
            ELSE NULL
        END,
        'source_catalog', 'ABVC Master Source'
    )),
    source_type = CASE
        WHEN LOWER(c.catalog_type) = 'facebook'
             AND LOWER(COALESCE(s.config->>'url', c.source_url)) LIKE '%facebook.com%'
            THEN 'social_media'
        ELSE s.source_type
    END,
    updated_at = NOW()
FROM abvc_catalog c
WHERE LOWER(RTRIM(COALESCE(s.config->>'url', ''), '/')) = LOWER(RTRIM(c.source_url, '/'));

COMMIT;
