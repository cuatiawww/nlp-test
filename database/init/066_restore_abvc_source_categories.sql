-- Restore ABVC Alma catalog categories onto sources seeded as generic "web".
-- Collector engine type stays rss/web/social_media/api so scrapers keep working.
-- Catalog type/official status/from_engine are stored in config for the UI.
-- Sources remain disabled.
BEGIN;

CREATE OR REPLACE FUNCTION abvc_source_credibility_type(config jsonb, source_type text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE LOWER(BTRIM(COALESCE(NULLIF(config->>'catalog_type', ''), source_type)))
    WHEN 'official government sites' THEN 'government'
    WHEN 'local news' THEN 'news'
    WHEN 'google' THEN 'web'
    WHEN 'facebook' THEN 'social_media'
    WHEN 'html' THEN 'web'
    WHEN 'chart' THEN 'web'
    WHEN 'json' THEN 'api'
    WHEN 'xml' THEN 'rss'
    ELSE LOWER(source_type)
  END;
$$;

